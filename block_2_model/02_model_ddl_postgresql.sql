-- Target PostgreSQL DDL (logical target model).
-- This is a target-schema proposal; SQLite build SQL is provided separately.
-- Do not interpret updated_at as authoritative version order until owner confirms semantics.

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS mart;

CREATE TABLE IF NOT EXISTS core.po_header (
  order_id text PRIMARY KEY,
  supplier_id text,
  order_dttm_msk timestamp without time zone,
  currency text,
  delivery_city text,
  order_type text
);

-- Grain: one observed source version/row of an order line.
-- source_row_no preserves row-level lineage; no unsafe "latest version" deduplication.
CREATE TABLE IF NOT EXISTS core.po_line_version (
  line_version_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_row_no bigint NOT NULL UNIQUE,
  order_id text NOT NULL REFERENCES core.po_header(order_id),
  line_no text NOT NULL,
  item_id text,
  qty numeric(20,6),
  price numeric(20,6),
  plan_price numeric(20,6),
  uom_code text,
  planned_delivery_date date,
  status text,
  updated_at timestamp without time zone,
  version_resolution_status text NOT NULL DEFAULT 'unresolved'
);

CREATE INDEX IF NOT EXISTS ix_po_line_version_order_line
  ON core.po_line_version(order_id, line_no);
CREATE INDEX IF NOT EXISTS ix_po_line_version_item
  ON core.po_line_version(item_id);
CREATE INDEX IF NOT EXISTS ix_po_line_version_updated_at
  ON core.po_line_version(updated_at);

-- Grain: one receipt event as observed from the WMS/Kafka extract.
-- receipt_id uniqueness is observed in this snapshot, not yet guaranteed by contract.
CREATE TABLE IF NOT EXISTS core.fact_receipt (
  receipt_id text PRIMARY KEY,
  order_id text NOT NULL,
  line_no text NOT NULL,
  received_at_utc timestamptz,
  qty_received numeric(20,6),
  quality_status text,
  warehouse_code text
);
CREATE INDEX IF NOT EXISTS ix_receipt_order_line
  ON core.fact_receipt(order_id, line_no);
CREATE INDEX IF NOT EXISTS ix_receipt_received_at
  ON core.fact_receipt(received_at_utc);

-- SCD2-style supplier versions. Validity interval is intended as [valid_from, valid_to);
-- confirm the boundary convention with the source owner before using for official reporting.
CREATE TABLE IF NOT EXISTS core.supplier_version (
  supplier_version_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id text NOT NULL,
  inn text,
  supplier_name text,
  region text,
  reliability_class text,
  valid_from date,
  valid_to date,
  is_current boolean,
  CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);
CREATE INDEX IF NOT EXISTS ix_supplier_version_asof
  ON core.supplier_version(supplier_id, valid_from, valid_to);

CREATE TABLE IF NOT EXISTS core.dim_item (
  item_id text PRIMARY KEY,
  item_name text,
  category text,
  category_reported text,
  uom_code text
);
CREATE TABLE IF NOT EXISTS core.dim_uom (
  uom_code text PRIMARY KEY,
  uom_name text,
  base_uom text,
  factor_to_base numeric(20,10),
  CHECK (factor_to_base IS NULL OR factor_to_base > 0)
);
CREATE TABLE IF NOT EXISTS core.dim_fx_rate (
  rate_date date NOT NULL,
  currency text NOT NULL,
  rate_to_rub numeric(20,10),
  PRIMARY KEY(rate_date, currency),
  CHECK (rate_to_rub IS NULL OR rate_to_rub > 0)
);

-- Grain: one observed order-line version enriched with reference attributes.
CREATE TABLE IF NOT EXISTS mart.order_line_versions (
  line_version_sk bigint PRIMARY KEY,
  source_row_no bigint NOT NULL,
  order_id text NOT NULL,
  line_no text NOT NULL,
  item_id text,
  item_name text,
  category text,
  ordered_qty numeric(20,6),
  unit_price numeric(20,6),
  currency text,
  plan_price numeric(20,6),
  uom_code text,
  base_uom text,
  factor_to_base numeric(20,10),
  planned_delivery_date date,
  status text,
  updated_at timestamp without time zone,
  version_resolution_status text NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_mart_order_line_versions_item
  ON mart.order_line_versions(item_id);
CREATE INDEX IF NOT EXISTS ix_mart_order_line_versions_category
  ON mart.order_line_versions(category);

-- Grain: one (order_id, line_no) pair; pre-aggregated receipts prevent join fanout.
CREATE TABLE IF NOT EXISTS mart.receipts_by_order_line (
  order_id text NOT NULL,
  line_no text NOT NULL,
  receipt_event_count bigint NOT NULL,
  qty_received_total numeric(20,6),
  first_received_at_utc timestamptz,
  last_received_at_utc timestamptz,
  PRIMARY KEY(order_id, line_no)
);
